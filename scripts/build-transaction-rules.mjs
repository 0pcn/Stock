import { readFile, writeFile } from 'node:fs/promises';
const source = await readFile(new URL('../lib/transaction-input.mjs', import.meta.url), 'utf8');
const expected = '// Generated by scripts/build-transaction-rules.mjs. Edit lib/transaction-input.mjs.\n' + source.replace('export function validateTransaction(', 'function stockfolioValidateTransaction_(').replace(/(\d)_(?=\d)/g, '$1');
const target = new URL('../google-apps-script/transaction-rules.gs', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== expected) throw new Error('Run node scripts/build-transaction-rules.mjs to update Apps Script transaction validation.');
} else await writeFile(target, expected);
